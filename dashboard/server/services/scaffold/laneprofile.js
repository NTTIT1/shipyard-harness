import fs from 'fs';
import path from 'path';
import { readText } from './util.js';
import { HEALTH_PATH } from './fullstack.js';

// Multi-project lanes: a project Shipyard generated (its .shipyard/project.json says which stack sits
// where) gets a harness profile — profiles/<slug>/ with profile.env, integrations.env and the lifecycle
// hooks (bootstrap, boot, health, ci-gate…) written for that stack — so lanes can clone and work on it
// next to the install's main project. Lanes share the harness Postgres (one DB per lane).

export const GENERATED_MARK = 'SHIPYARD_GENERATED=1';
const SLUG_RE = /^[a-z][a-z0-9-]{2,39}$/;
const BACKENDS = ['java-spring', 'python-fastapi', 'ts-nestjs'];
const FRONTENDS = ['ts-react-vite'];
const IMAGE = { java: 'maven:3.9-eclipse-temurin-21', node: 'node:22-bookworm', python: 'python:3.12-bookworm' };

/** Where each app of the project lives, from .shipyard/project.json. */
export function projectParts(projectDir) {
  let meta;
  try { meta = JSON.parse(readText(path.join(projectDir, '.shipyard', 'project.json'))); } catch { meta = null; }
  if (!meta?.slug) throw new Error('Không phải dự án do Shipyard tạo (thiếu .shipyard/project.json)');
  if (meta.kind === 'fullstack') {
    return { meta, backend: { dir: meta.backend.dir || 'backend', stack: meta.backend.stack, options: meta.backend.options || {} },
      frontend: { dir: meta.frontend.dir || 'frontend', stack: meta.frontend.stack, options: meta.frontend.options || {} } };
  }
  const part = { dir: '.', stack: meta.stack, options: meta.options || {} };
  if (BACKENDS.includes(meta.stack)) return { meta, backend: part, frontend: null };
  if (FRONTENDS.includes(meta.stack)) return { meta, backend: null, frontend: part };
  throw new Error(`Chưa hỗ trợ lane cho stack ${meta.stack}`);
}

const pkg = slug => slug.replace(/-/g, '_');
// run_hook exports the lane contract (LANE_DIR, API_PORT…) but not profile.env's keys: read them here.
const HEAD = name => `#!/usr/bin/env bash\n# ${name} — generated by Shipyard for this project's stack (see profile.env). Edit freely.\nset -euo pipefail\n# shellcheck disable=SC1091\nsource "$PROFILE_DIR/profile.env"\n`;
// The app reads DB_HOST/DB_PORT/DB_NAME/DB_USER/DB_PASSWORD (Shipyard's env names); point them at the
// harness Postgres and this lane's database (or its _test twin in CI), SQLite at a per-lane file.
const DB_ENV = db => {
  if (db === 'postgresql') return 'export DB_HOST="$PG_HOST" DB_PORT="$PG_PORT" DB_USER="$PG_USER" DB_PASSWORD="$PG_PASS" DB_NAME="${DB_NAME_OVERRIDE:-$DB_NAME}"\n';
  if (db === 'sqlite') return 'mkdir -p "$LANE_DIR/data"; export SQLITE_PATH="$LANE_DIR/data/app.db"\n';
  if (db === 'redis') return 'export REDIS_HOST="$REDIS_HOST" REDIS_PORT="$REDIS_PORT"\n';
  return '';
};
const BE = '"$LANE_DIR/$BACKEND_DIR"', FE = '"$LANE_DIR/$FRONTEND_DIR"';

function backendHooks(b, slug) {
  const db = b.options.db || 'none';
  switch (b.stack) {
    case 'java-spring': {
      const build = 'if [ -x ./mvnw ]; then BUILD=(./mvnw -q -B); RUN=(./mvnw -q spring-boot:run); else BUILD=(./gradlew -q); RUN=(./gradlew -q bootRun); fi\n';
      return {
        bootstrap: `( cd ${BE} && ${build.trim()} && if [ -x ./mvnw ]; then "\${BUILD[@]}" -DskipTests dependency:go-offline; else "\${BUILD[@]}" dependencies >/dev/null; fi ) || echo "bootstrap: dependency prefetch failed (will retry at build)" >&2\n`,
        boot: `${DB_ENV(db)}cd ${BE}\n${build}harness_spawn api ${BE} env PORT="$API_PORT" "\${RUN[@]}"\n`,
        health: `curl -fsS --retry 90 --retry-delay 2 --retry-connrefused --max-time 5 "http://localhost:$API_PORT${HEALTH_PATH['java-spring']}" >/dev/null\n`,
        gate: `DB_NAME_OVERRIDE="\${TEST_DATABASE_URL##*/}"\n${DB_ENV(db)}( cd ${BE} && ${build.trim()} && if [ -x ./mvnw ]; then "\${BUILD[@]}" test; else "\${BUILD[@]}" test; fi )\n`,
        image: IMAGE.java,
      };
    }
    case 'python-fastapi':
      return {
        bootstrap: `( cd ${BE} && uv sync )\n`,
        boot: `${DB_ENV(db)}harness_spawn api ${BE} env PORT="$API_PORT" uv run uvicorn ${pkg(slug)}.main:app --app-dir src --host 0.0.0.0 --port "$API_PORT"\n`,
        health: `curl -fsS --retry 60 --retry-delay 2 --retry-connrefused --max-time 5 "http://localhost:$API_PORT${HEALTH_PATH['python-fastapi']}" >/dev/null\n`,
        gate: `DB_NAME_OVERRIDE="\${TEST_DATABASE_URL##*/}"\n${DB_ENV(db)}( cd ${BE} && uv run pytest -q )\n`,
        image: IMAGE.python,
      };
    case 'ts-nestjs':
      return {
        bootstrap: `( cd ${BE} && (npm ci --no-audit --no-fund --prefer-offline || npm install --no-audit --no-fund --prefer-offline) )\n`,
        boot: `${DB_ENV(db)}harness_spawn api ${BE} env PORT="$API_PORT" npm run start:dev\n`,
        health: `curl -fsS --retry 60 --retry-delay 2 --retry-connrefused --max-time 5 "http://localhost:$API_PORT${HEALTH_PATH['ts-nestjs']}" >/dev/null\n`,
        gate: `DB_NAME_OVERRIDE="\${TEST_DATABASE_URL##*/}"\n${DB_ENV(db)}( cd ${BE} && npm run build && npm test )\n`,
        image: IMAGE.node,
      };
    default: throw new Error(`Chưa hỗ trợ lane cho backend ${b.stack}`);
  }
}

function frontendHooks(f) {
  if (f.stack !== 'ts-react-vite') throw new Error(`Chưa hỗ trợ lane cho frontend ${f.stack}`);
  const test = f.options.tests === false ? '' : ' && npm test';
  return {
    bootstrap: `( cd ${FE} && (npm ci --no-audit --no-fund --prefer-offline || npm install --no-audit --no-fund --prefer-offline) )\n`,
    // BACKEND_PORT: the Vite /api proxy Shipyard generated follows it to this lane's backend.
    boot: `harness_spawn fe ${FE} env BACKEND_PORT="$API_PORT" npx vite --port "$FE_PORT" --strictPort --host 0.0.0.0\n`,
    health: 'curl -fsS --retry 60 --retry-delay 2 --retry-connrefused --max-time 5 "$FE_URL/" >/dev/null\n',
    gate: `"$HARNESS_ROOT/bin/with-lock.sh" build -- bash -c "cd '$LANE_DIR/$FRONTEND_DIR' && npm run build${test}"\n`,
    image: IMAGE.node,
  };
}

/** profile.env + integrations.env + hooks/*.sh for the project, as { relativePath: content }. */
export function laneProfileFiles(projectDir, { projectId = '', name = '' } = {}) {
  const { meta, backend, frontend } = projectParts(projectDir);
  const be = backend ? backendHooks(backend, meta.slug) : null;
  const fe = frontend ? frontendHooks(frontend) : null;
  const parts = [be, fe].filter(Boolean);
  const db = backend?.options?.db || 'none';
  if (['mysql', 'mongodb'].includes(db)) throw new Error(`Lane dùng Postgres chung của harness — chưa hỗ trợ database ${db} cho lane`);
  const join = key => parts.map(p => p[key]).join('');
  const stackLine = [backend && `${backend.dir === '.' ? '' : `${backend.dir}/ `}${backend.stack}`, frontend && `${frontend.dir === '.' ? '' : `${frontend.dir}/ `}${frontend.stack}`]
    .filter(Boolean).join(' + ');
  const extra = backend?.stack === 'java-spring' && frontend ? 'nodejs npm' : '';
  const files = {
    'profile.env': [
      `# Harness profile generated by Shipyard for ${name || meta.name} (${stackLine}).`,
      '# Lanes bound to this project (lane-add.sh --profile) read it. Remove the next line to stop Shipyard regenerating it.',
      GENERATED_MARK,
      `BACKEND_DIR="${backend?.dir || '.'}"`,
      `FRONTEND_DIR="${frontend?.dir || '.'}"`,
      'API_PATH=""',
      'DB_SERVICE="postgres"',
      'BASE_BRANCH="development"',
      'INTEGRATION_BRANCH="development"',
      'BRANCH_PREFIX="feat/"',
      `TEST_PATHS="${[backend && 'src/test/ tests/ *.spec.ts', frontend && '*.test.tsx *.test.ts'].filter(Boolean).join(' ')}"`,
      'GENERATED_MERGE_PATHS=""',
      'MIGRATIONS_DIR=""',
      'QC_BOOT_ENV=""',
      `OPENHANDS_BASE_IMAGE="\${OPENHANDS_BASE_IMAGE:-${parts[0].image}}"`,
      `OPENHANDS_EXTRA_PACKAGES="\${OPENHANDS_EXTRA_PACKAGES:-${extra}}"`,
      'IMPL_AGENTS="1"',
      '',
    ].join('\n'),
    'integrations.env': [
      `# Integrations for ${meta.slug} (generated by Shipyard). The platform project makes its lanes run the role pipeline.`,
      `PLATFORM_PROJECT_ID="${projectId}"`,
      'TRACKER_ENABLED="0"',
      'DEV_QC_ENABLED="0"',
      'CI_WAIT_ENABLED="0"',
      '',
    ].join('\n'),
    'hooks/bootstrap.sh': HEAD('bootstrap: install dependencies') + join('bootstrap'),
    'hooks/boot.sh': HEAD('boot: start this lane\'s app in the background, then return') + join('boot'),
    'hooks/health.sh': HEAD('health: exit 0 when the lane\'s app answers') + join('health'),
    'hooks/ci-gate.sh': HEAD('ci-gate: build + tests before a push (TEST_DATABASE_URL = an isolated DB)') + join('gate'),
    'hooks/migrate.sh': HEAD('migrate') + 'echo "migrate: schema is managed by the app at boot (no separate migration step)"\n',
    'hooks/seed.sh': HEAD('seed') + 'echo "seed: no initial user to create for this project"\n',
    'hooks/e2e.sh': HEAD('e2e') + 'echo "e2e: this project has no end-to-end suite yet — skipped"\n',
    'hooks/regen.sh': HEAD('regen') + 'exit 0\n',
  };
  return { slug: meta.slug, files };
}

/**
 * Writes profiles/<slug>/ for the project (overwriting only a profile Shipyard generated before, never a
 * hand-made one). Returns the profile name.
 */
export function writeLaneProfile(harnessRoot, projectDir, opts = {}) {
  const { slug, files } = laneProfileFiles(projectDir, opts);
  if (!SLUG_RE.test(slug)) throw new Error(`slug không hợp lệ: ${slug}`);
  const dir = path.join(harnessRoot, 'profiles', slug);
  const existing = readText(path.join(dir, 'profile.env'));
  if (existing && !existing.includes(GENERATED_MARK)) throw new Error(`profiles/${slug} đã có và do người viết — không ghi đè`);
  for (const [rel, text] of Object.entries(files)) {
    const f = path.join(dir, rel);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, text);
    if (rel.startsWith('hooks/')) fs.chmodSync(f, 0o755);
  }
  return slug;
}
